function controlChart(
  analyteName: string,
  unit: string,
  mean: number,
  sd: number,
  lotNumber: string,
  offsets: readonly number[] = CONTROL_OFFSETS,
) {
  return {
    analyteName,
    unit,
    mean,
    sd,
    lotNumber,
    points: offsets.map((offset, index) => ({
      runLabel: `S${index + 1}`,
      value: Math.round((mean + offset * sd) * 1000) / 1000,
    })),
  };
}

function monoclonalGammaCurve(): number[] {
  const curve: number[] = [];
  for (let index = 0; index < 72; index += 1) {
    const x = index / 71;
    const density =
      70 * Math.exp(-((x - 0.14) ** 2) / 0.004) +
      8 * Math.exp(-((x - 0.28) ** 2) / 0.002) +
      14 * Math.exp(-((x - 0.4) ** 2) / 0.003) +
      12 * Math.exp(-((x - 0.55) ** 2) / 0.0025) +
      8 * Math.exp(-((x - 0.64) ** 2) / 0.002) +
      16 * Math.exp(-((x - 0.76) ** 2) / 0.01) +
      48 * Math.exp(-((x - 0.86) ** 2) / 0.0007);
    curve.push(Math.round(density * 10) / 10);
  }
  return curve;
}

